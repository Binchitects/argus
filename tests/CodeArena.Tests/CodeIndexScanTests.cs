namespace CodeArena.Tests;

/// <summary>
/// What the code index scans: code with its comments and strings blanked (Argus's CodeText, shared as a file), every line
/// where it was, so a symbol's range in the blanked text is its range in the file, and a brace in a string counts for nothing.
/// </summary>
public sealed class CodeIndexScanTests
{
    [Theory]
    [InlineData("csharp", "var s = \"\"\"\n  { not a block }\n  \"\"\";\nclass A { }\n")]
    [InlineData("csharp", "var t = $\"{a} } {{\"; // }\nclass B { void M() { } }\n")]
    [InlineData("typescript", "const t = `a ${b} }\n}`\nfunction f() { return 1 }\n")]
    [InlineData("python", "s = '''\ndef not_a_function():\n'''\ndef real():\n    pass\n")]
    public void Blanked_code_keeps_its_lines_and_its_braces_balance(string lang, string text)
    {
        var blanked = Argus.Util.CodeText.Blank(lang, text);
        Assert.Equal(text.Split('\n').Length, blanked.Split('\n').Length);
        Assert.Equal(blanked.Count(c => c == '{'), blanked.Count(c => c == '}'));
        Assert.DoesNotContain("not a", blanked, StringComparison.Ordinal);
    }

    [Fact]
    public void Import_strings_stay_when_asked()
    {
        Assert.Contains("\"./api\"", Argus.Util.CodeText.Blank("typescript", "import { a } from \"./api\" // where", keepStrings: true), StringComparison.Ordinal);
    }
}

/// <summary>The files the code index covers: those grep sees, less binaries, with secrets listed but never read.</summary>
public sealed class CodeFilesTests : IDisposable
{
    private readonly string _root = Directory.CreateTempSubdirectory("code-files-").FullName;

    public void Dispose() => Directory.Delete(_root, recursive: true);

    private void Write(string path, string text)
    {
        var full = Path.Combine(_root, path);
        Directory.CreateDirectory(Path.GetDirectoryName(full)!);
        File.WriteAllText(full, text);
    }

    private static void Git(string dir, params string[] args)
    {
        var psi = new System.Diagnostics.ProcessStartInfo("git") { WorkingDirectory = dir, RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false };
        foreach (var arg in args)
        {
            psi.ArgumentList.Add(arg);
        }
        using var git = System.Diagnostics.Process.Start(psi)!;
        git.StandardOutput.ReadToEnd();
        git.StandardError.ReadToEnd();
        Assert.True(git.WaitForExit(30_000));
    }

    [Fact]
    public void The_index_sees_what_grep_sees_and_never_reads_a_secret()
    {
        Git(_root, "init", "-q");
        Write(".gitignore", "*.log\n");
        Write("src/App.cs", "class App { }\n");
        Write("src/TokenCounter.cs", "class TokenCounter { }\n");
        Write("src/Data/Model.Designer.cs", "// <auto-generated />\npartial class Model { }\n");
        Write("tests/AppTests.cs", "class AppTests { }\n");
        Write("web/api.test.ts", "test('x', () => {})\n");
        Write("docs/guide.md", "# Guide\n");
        Write(".env", "KEY=value\n");
        Write(".env.example", "KEY=\n");
        Write("deploy/id_rsa", "-----BEGIN OPENSSH PRIVATE KEY-----\n");
        Write("secrets/db.yaml", "password: x\n");
        Write("certs/site.pem", "-----BEGIN CERTIFICATE-----\n");
        Write("config/db-password.txt", "x\n");
        Write("build.log", "ignored\n");
        File.WriteAllBytes(Path.Combine(_root, "logo.bin"), [0, 1, 2, 0, 255]);
        Git(_root, "add", ".gitignore", "src", "docs");
        var files = CodeFiles.List(new Workspace(_root), [_root], CancellationToken.None).ToDictionary(f => f.Path);

        // As grep sees them: the git-ignored file left out, the untracked ones in; a binary left out.
        Assert.DoesNotContain("build.log", files.Keys);
        Assert.DoesNotContain("logo.bin", files.Keys);
        Assert.Contains("tests/AppTests.cs", files.Keys);
        // Secrets are listed so the index can say it skipped them; their contents are never read.
        Assert.All(new[] { ".env", "deploy/id_rsa", "secrets/db.yaml", "certs/site.pem", "config/db-password.txt" },
            p => Assert.True(files[p].Tags.HasFlag(CodeFileTags.Sensitive), p));
        Assert.False(files[".env.example"].Tags.HasFlag(CodeFileTags.Sensitive));
        Assert.False(files["src/TokenCounter.cs"].Tags.HasFlag(CodeFileTags.Sensitive));
        // What each file is for, and its language.
        Assert.Equal(("csharp", CodeFileTags.None), (files["src/App.cs"].Lang, files["src/App.cs"].Tags));
        Assert.True(files["src/Data/Model.Designer.cs"].Tags.HasFlag(CodeFileTags.Generated));
        Assert.True(files["tests/AppTests.cs"].Tags.HasFlag(CodeFileTags.Test));
        Assert.True(files["web/api.test.ts"].Tags.HasFlag(CodeFileTags.Test));
        Assert.Equal(("markdown", CodeFileTags.Docs), (files["docs/guide.md"].Lang, files["docs/guide.md"].Tags));
    }

    [Theory]
    [InlineData("key = \"AKIA" + "ABCDEFGHIJKLMNOP\"", true)]
    [InlineData("-----BEGIN RSA PRIVATE KEY-----", true)]
    [InlineData("var token = Config.Token;", false)]
    public void Text_that_holds_a_secret_is_found(string text, bool secret) => Assert.Equal(secret, CodeFiles.HoldsSecret(text));
}
